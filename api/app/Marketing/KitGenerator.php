<?php

namespace App\Marketing;

use App\Models\Book;
use App\Models\ManuscriptSection;
use RuntimeException;

/**
 * Builds launch copy from the manuscript.
 *
 * Deliberately extractive, not inventive. Every sentence it produces is
 * either the author's own words, or a frame around them — it pulls the
 * opening claim, the chapter titles and the clearest sentences, and arranges
 * them. It does not write new claims about a book it has not read properly.
 *
 * That matters more here than anywhere else in the product: marketing copy
 * goes out under the author's name to people deciding whether to buy, and an
 * invented statistic or promise in a store listing is the author's problem,
 * not the generator's. When a real provider is wired in behind the editorial
 * seam this becomes the fallback rather than the only implementation, and the
 * same rule should hold for whatever replaces it.
 */
class KitGenerator
{
    public function generate(Book $book, ?string $audience = null): array
    {
        $chapters = $book->sections()
            ->where('type', '!=', 'part')
            ->orderBy('position')
            ->get()
            ->filter(fn (ManuscriptSection $s) => trim($s->plainText()) !== '')
            ->values();

        if ($chapters->isEmpty()) {
            throw new RuntimeException('Write a chapter before generating a kit.');
        }

        $audience = trim((string) ($audience ?? $this->guessAudience($book)));
        $title = $book->title;
        $author = $book->author_name ?: 'the author';

        $opening = $this->bestSentence($chapters->first());
        $titles = $chapters->take(6)->map(fn ($c) => $c->title)->all();

        return [
            'audience' => $audience,
            'description' => $this->description($book, $opening, $titles, $audience),
            'email' => $this->email($title, $author, $opening, $audience),
            'posts' => $this->posts($book, $opening, $titles),
            'generated_at' => now()->toIso8601String(),
            // Named so the screen can say where the copy came from, and so a
            // kit generated by a real provider later is distinguishable from
            // one assembled from the author's own sentences.
            'source' => 'extractive',
        ];
    }

    /**
     * The clearest sentence in a chapter.
     *
     * "Clearest" is a length band, not a judgement: long enough to carry a
     * claim, short enough to read as a line of marketing copy. Picking the
     * first sentence instead would usually return a chapter heading or a
     * scene-setting clause.
     */
    private function bestSentence(ManuscriptSection $section): string
    {
        $sentences = preg_split('/(?<=[.!?])\s+/', $section->plainText()) ?: [];

        $candidates = array_filter($sentences, function (string $sentence): bool {
            $words = str_word_count($sentence);

            return $words >= 10 && $words <= 28 && ! str_ends_with(trim($sentence), ':');
        });

        return trim($candidates ? reset($candidates) : (string) ($sentences[0] ?? ''));
    }

    /** @param array<int, string> $titles */
    private function description(Book $book, string $opening, array $titles, string $audience): string
    {
        $existing = trim((string) (($book->meta ?? [])['description'] ?? ''));

        // An author who has already written a listing has said how they want
        // the book described. Replacing it would be presumptuous.
        if ($existing !== '') {
            return $existing;
        }

        $covered = count($titles) > 1
            ? 'It covers '.$this->sentenceList(array_slice($titles, 0, 4)).'.'
            : '';

        return trim(
            $opening."\n\n"
            ."{$book->title} is written for {$audience}. {$covered}"
        );
    }

    /** @return array<string, string> */
    private function email(string $title, string $author, string $opening, string $audience): array
    {
        return [
            'subject' => "{$title} is out",
            'body' => implode("\n\n", [
                'Hello,',
                "My book, {$title}, is available now.",
                $opening,
                "I wrote it for {$audience}, and I would be glad to know what you make of it.",
                'Thank you for reading,',
                $author,
            ]),
        ];
    }

    /**
     * Short posts, each within the tightest common limit.
     *
     * @param  array<int, string>  $titles
     * @return array<int, string>
     */
    private function posts(Book $book, string $opening, array $titles): array
    {
        $posts = [
            "{$book->title} is out now.\n\n".$this->trimTo($opening, 180),
        ];

        if ($titles !== []) {
            $posts[] = "What is in {$book->title}:\n\n"
                .implode("\n", array_map(fn ($t) => "· {$t}", array_slice($titles, 0, 4)));
        }

        if ($book->subtitle) {
            $posts[] = "{$book->title}\n{$book->subtitle}\n\nAvailable now.";
        }

        // 280 is the tightest limit among the usual places; copy that fits
        // everywhere is more useful than copy an author has to cut by hand.
        return array_map(fn (string $post) => $this->trimTo($post, 280), $posts);
    }

    private function trimTo(string $text, int $limit): string
    {
        if (mb_strlen($text) <= $limit) {
            return $text;
        }

        // Cut at a word boundary, so the copy never ends mid-word.
        $cut = mb_substr($text, 0, $limit - 1);
        $space = mb_strrpos($cut, ' ');

        return rtrim($space === false ? $cut : mb_substr($cut, 0, $space), " ,.;:").'…';
    }

    /** @param array<int, string> $items */
    private function sentenceList(array $items): string
    {
        if (count($items) === 1) {
            return $items[0];
        }

        $last = array_pop($items);

        return implode(', ', $items).' and '.$last;
    }

    /**
     * A reader description from the book's own category.
     *
     * A starting point the author edits, not a claim about who will buy it.
     */
    private function guessAudience(Book $book): string
    {
        $category = (string) (($book->meta ?? [])['category'] ?? '');

        return match (true) {
            str_contains($category, 'Medical') => 'clinicians and practice owners',
            str_contains($category, 'Business') => 'people running a small business',
            str_contains($category, 'Self-Help') => 'readers working on something difficult',
            str_contains($category, 'Education') => 'people teaching in their field',
            default => 'readers of '.($book->genre ?: 'this subject'),
        };
    }
}
