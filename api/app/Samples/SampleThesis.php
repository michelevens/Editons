<?php

namespace App\Samples;

use App\Import\ImportReport;
use App\Import\MarkdownImporter;
use App\Models\Book;
use App\Models\Citation;
use App\Models\ManuscriptSection;
use App\Models\User;
use App\Research\Bibliography;
use App\Services\ManuscriptWriter;
use Illuminate\Support\Facades\DB;
use InvalidArgumentException;
use ReflectionMethod;

/**
 * The four complete sample theses, built into an account from the files in
 * resources/samples/{slug}.
 *
 * Each sample is the product working end to end: a reading list loaded as
 * research sources, every {{key}} citation token turned into a citation
 * record and printed in the book's own style, numbered in order of first
 * citation where the style numbers, and a References section generated by
 * Bibliography. The institutions, people and data are fictional or
 * synthetic and each book says so; the cited works are real.
 *
 * Kept in the repository rather than loaded by hand, because the demo
 * account is rebuilt on every deploy and hand-loaded books went with it.
 */
class SampleThesis
{
    public const SLUGS = ['m-qual', 'm-proj', 'phd-mixed', 'phd-3p'];

    private const TOKEN = '/\{\{([^}|]+)(?:\|([^}]+))?\}\}/u';

    private const SPEC_KEYS = ['kind', 'title', 'authors', 'publisher', 'published', 'container', 'volume', 'issue', 'pages', 'edition', 'url', 'doi', 'notes'];

    public function __construct(
        private readonly Bibliography $bibliography,
        private readonly MarkdownImporter $importer,
        private readonly ManuscriptWriter $writer,
    ) {}

    public function load(User $user, string $slug): Book
    {
        if (! in_array($slug, self::SLUGS, true)) {
            throw new InvalidArgumentException("No sample thesis called {$slug}.");
        }

        $directory = resource_path("samples/{$slug}");
        $meta = json_decode((string) file_get_contents("{$directory}/meta.json"), true);
        $refs = json_decode((string) file_get_contents("{$directory}/refs.json"), true);

        return DB::transaction(function () use ($user, $meta, $refs, $directory) {
            $book = $user->books()->create([
                'title' => $meta['title'],
                'subtitle' => $meta['subtitle'],
                'author_name' => $meta['author'],
                'book_type' => $meta['type'],
                'genre' => $meta['genre'],
                'premise' => $meta['premise'],
                'audience' => $meta['audience'],
                'description' => 'An illustrative sample shipped with Ecrivain. The institution, people and data are fictional or synthetic; the cited works are real. Not for submission.',
                'settings' => array_merge(Book::DEFAULT_SETTINGS, ['citation_style' => $meta['style']]),
            ]);

            $sources = [];
            foreach ($refs as $ref) {
                $source = $book->sources()->create(array_intersect_key($ref, array_flip(self::SPEC_KEYS)));
                $source->added_by = $user->id;
                $source->save();
                $sources[$ref['key']] = $source;
            }

            $sections = [];
            $markdown = [];
            $position = 0;

            foreach ($meta['sections'] as $spec) {
                $position += ManuscriptSection::POSITION_STEP;
                $section = $book->sections()->create([
                    'type' => $spec['type'],
                    'title' => $spec['title'],
                    'position' => $position,
                    'content' => ['type' => 'doc', 'content' => []],
                ]);
                $sections[] = [$spec, $section];

                if ($spec['file']) {
                    $md = str_replace(["\r\n", "\r"], "\n", (string) file_get_contents("{$directory}/sections/{$spec['file']}"));
                    $markdown[$section->id] = preg_replace('/^\s*#\s+.+\n/', '', ltrim($md));
                }
            }

            $this->cite($sections, $markdown, $sources, $user);

            $style = $meta['style'];
            $entries = $this->bibliography->forBook($book->fresh(), $style);
            $numbers = array_column($entries, 'number', 'id');
            $convert = new ReflectionMethod($this->importer, 'toProseMirror');

            foreach ($sections as [$spec, $section]) {
                if (isset($markdown[$section->id])) {
                    $md = preg_replace_callback(self::TOKEN, fn ($m) => $this->inText(
                        array_map('trim', explode(';', $m[1])), $m[2] ?? null, $sources, $numbers, $style,
                    ), $markdown[$section->id]);
                    $md = preg_replace('/^(#{1,6}\s+.+)$/m', "\n$1\n", $md);
                    $md = trim(preg_replace("/\n{3,}/", "\n\n", $md))."\n";

                    $this->writer->save(
                        section: $section,
                        content: $convert->invoke($this->importer, $md, new ImportReport),
                        reason: 'ai_draft',
                        userId: $user->id,
                        label: 'Ecrivain sample thesis: illustrative, not for submission',
                    );
                } elseif ($spec['title'] === 'References') {
                    $this->writer->save(
                        section: $section,
                        content: ['type' => 'doc', 'content' => array_map(fn ($e) => $this->entryParagraph($e['html']), $entries)],
                        reason: 'ai_draft',
                        userId: $user->id,
                        label: "Generated from the research library ({$style})",
                    );
                }
            }

            $book->refresh()->recalculateWordCount();

            return $book;
        });
    }

    /**
     * A citation per source per section, in reading order, so numbered
     * styles number sources by first appearance. The claim is the sentence
     * the citation sits in.
     */
    private function cite(array $sections, array $markdown, array $sources, User $user): void
    {
        foreach ($sections as [, $section]) {
            if (! isset($markdown[$section->id])) {
                continue;
            }

            $md = $markdown[$section->id];
            $seen = [];
            preg_match_all(self::TOKEN, $md, $all, PREG_SET_ORDER | PREG_OFFSET_CAPTURE);

            foreach ($all as $m) {
                foreach (array_map('trim', explode(';', $m[1][0])) as $key) {
                    if (isset($seen[$key]) || ! isset($sources[$key])) {
                        continue;
                    }
                    $seen[$key] = true;

                    $before = substr($md, 0, $m[0][1]);
                    $start = max(strrpos($before, '. ') ?: 0, strrpos($before, "\n") ?: 0);
                    $end = strpos($md, '.', $m[0][1] + strlen($m[0][0]));
                    $claim = trim(preg_replace([self::TOKEN, '/[*#>|]/', '/\s+/'], ['', '', ' '],
                        substr($md, $start, ($end === false ? strlen($md) : $end + 1) - $start)), " .\n");

                    Citation::create([
                        'manuscript_section_id' => $section->id,
                        'research_source_id' => $sources[$key]->id,
                        'created_by' => $user->id,
                        'claim' => mb_substr($claim ?: $sources[$key]->title, 0, 1000),
                        'status' => 'supported',
                    ]);
                }
            }
        }
    }

    /** The in-text citation for a token, in the book's style. */
    private function inText(array $keys, ?string $option, array $sources, array $numbers, string $style): string
    {
        $keys = array_values(array_filter($keys, fn ($k) => isset($sources[$k])));
        $numeric = in_array($style, Bibliography::NUMERIC, true);

        if ($keys === []) {
            return '[source needed]';
        }

        if ($option === 'n') {
            // Narrative: the authors as the subject of the sentence.
            $source = $sources[$keys[0]];
            [$who, $year] = array_map('trim', explode(', ', trim($this->bibliography->inText($source, 'APA'), '()'), 2) + [1 => '']);
            $who = str_replace(' & ', ' and ', $who);

            return $numeric
                ? $who.' '.$this->bibliography->inText($source, $style, $numbers[$source->id])
                : "{$who} ({$year})";
        }

        $parts = array_map(fn ($k) => $this->bibliography->inText($sources[$k], $style, $numbers[$sources[$k]->id]), $keys);
        $locator = $option ? ', '.$option : '';

        return match ($style) {
            'IEEE' => count($parts) === 1 ? '['.trim($parts[0], '[]').$locator.']' : implode(', ', $parts),
            'Vancouver' => '('.implode(',', array_map(fn ($p) => trim($p, '()'), $parts)).$locator.')',
            default => '('.implode('; ', array_map(fn ($p) => trim($p, '()'), $parts)).$locator.')',
        };
    }

    /** A bibliography entry's HTML as a paragraph, italics kept. */
    private function entryParagraph(string $html): array
    {
        $nodes = [];

        foreach (preg_split('/(<i>.*?<\/i>)/u', $html, -1, PREG_SPLIT_DELIM_CAPTURE | PREG_SPLIT_NO_EMPTY) as $piece) {
            $text = html_entity_decode(strip_tags($piece), ENT_QUOTES | ENT_HTML5, 'UTF-8');

            if ($text !== '') {
                $nodes[] = str_starts_with($piece, '<i>')
                    ? ['type' => 'text', 'text' => $text, 'marks' => [['type' => 'italic']]]
                    : ['type' => 'text', 'text' => $text];
            }
        }

        return ['type' => 'paragraph', 'content' => $nodes];
    }
}
