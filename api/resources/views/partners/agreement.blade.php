ÉCRIVAIN PARTNER AGREEMENT — VERSION 1 (DRAFT)

This is a draft. It has not been reviewed by a lawyer and will change before the program launches.

1. What you are agreeing to
You may share links to books sold in the Écrivain store, from your own partner page and anywhere else you choose. When somebody buys a book through your link, your page, your QR code or a discount code Écrivain gave you, you earn a commission on that sale.

2. Commissions
Each author decides whether partners may sell their book, and the rate: from {{ $rate['min'] }} % to {{ $rate['max'] }} % of what the buyer paid for the book, after any discount and after the payment processor's fee. The rate is fixed when the buyer starts their purchase. A commission is held for {{ $hold }} days, the refund window, before it can be paid. If the buyer is refunded, the commission is reduced in the same proportion; if it was already paid, the difference comes out of your next earnings.

3. What does not earn a commission
Buying for yourself, through your own link or code, or with your own email address. Books you sell yourself as an author. Books whose author has not let partners sell them, or who has asked not to work with you. Anything bought while your partner account is suspended. A link keeps the credit for {{ $cookie }} days, and the most recent partner link a buyer followed gets it; a partner discount code always does.

4. Being honest with readers
Your page always says that you earn a commission on purchases made through it. Say so as well wherever you share your links. Do not make claims about a book or its author that you cannot support, do not pretend to be the author or Écrivain, do not send spam, and do not pay or reward anybody for clicking or buying.

5. Payment
Écrivain pays you outside the app, by the method you choose in your dashboard (PayPal, MonCash or a bank transfer), once your balance reaches {{ $minimum }} in a currency. You are responsible for any tax on what you earn. Écrivain may ask you for a tax form before paying.

6. Suspension and ending
Écrivain may suspend your partner account if these rules are broken, if your page is reported and the report is upheld, or to investigate unusual activity. While suspended, your page is offline, your links do not earn, and your balance is frozen; after review it is either released to you or, if the rules were broken, forfeited. You may stop being a partner at any time by writing to support; what you have earned under these terms is still paid.

7. Changes
If this agreement changes, you will be asked to accept the new version. Commissions already earned keep the terms they were earned under.
