#!/usr/bin/env python3
"""Port the prototype's icon map into a React module.

HANDOFF.md says to use lucide-react where it matches the reference glyphs and
otherwise port the inline SVG paths. Rather than eyeballing fifty-one glyphs
against a library and getting some subtly wrong, all of them come from the
prototype, which the handoff names as the visual authority.

    python scripts/build-icons.py
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'publishing-studio-handoff' / 'prototype' / 'index.html'
TARGET = ROOT / 'resources' / 'js' / 'Components' / 'Studio' / 'Icon.jsx'

HEADER = '''/**
 * Icon paths ported verbatim from the handoff prototype's `P` map.
 *
 * GENERATED by scripts/build-icons.py -- do not edit by hand.
 *
 * Every path is drawn on a 24x24 viewBox with round caps and joins, matching
 * how the prototype renders them.
 */

export const ICON_PATHS = {
'''

COMPONENT = '''};

/**
 * One icon. `name` is a key of ICON_PATHS.
 *
 * Paths are multi-subpath strings rendered as a single <path>; the prototype
 * relies on stroke, not fill, for every glyph.
 */
export default function Icon({
    name,
    size = 19,
    className = '',
    strokeWidth = 1.7,
    ...rest
}) {
    const d = ICON_PATHS[name];

    if (!d) {
        // Loud in development, invisible in production: a missing glyph is a
        // typo worth catching, never a reason to break the page.
        if (import.meta.env.DEV) {
            console.warn(`Icon "${name}" is not in ICON_PATHS.`);
        }

        return null;
    }

    return (
        <svg
            viewBox="0 0 24 24"
            width={size}
            height={size}
            fill="none"
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            strokeLinejoin="round"
            aria-hidden="true"
            focusable="false"
            className={className}
            {...rest}
        >
            <path d={d} />
        </svg>
    );
}
'''


def extract_map(source: str, name: str) -> str:
    """Return the brace-balanced body of `const <name> = { ... }`."""
    match = re.search(r'const ' + name + r'\s*=\s*\{', source)

    if not match:
        raise SystemExit(f'Could not find `const {name}` in the prototype.')

    start = match.end() - 1
    depth = 0

    for index in range(start, len(source)):
        if source[index] == '{':
            depth += 1
        elif source[index] == '}':
            depth -= 1

            if depth == 0:
                return source[start + 1:index]

    raise SystemExit(f'`const {name}` is not brace-balanced.')


def main() -> None:
    source = SOURCE.read_text(encoding='utf-8')
    body = extract_map(source, 'P')

    pairs = re.findall(r'(\w+)\s*:\s*([`\'"])(.*?)\2', body, re.S)

    if not pairs:
        raise SystemExit('No icon paths parsed.')

    lines = [HEADER]

    for key, _quote, path in pairs:
        # json.dumps gives correctly escaped, double-quoted JS string
        # literals, which is safer than hand-rolling backslash handling.
        lines.append(f'    {key}: {json.dumps(path)},')

    lines.append(COMPONENT)

    TARGET.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {TARGET.relative_to(ROOT)} with {len(pairs)} glyphs')


if __name__ == '__main__':
    main()
